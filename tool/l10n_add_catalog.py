def main() -> int:
    path = ROOT / "lib" / "l10n" / "en_catalog.dart"
    source = path.read_text(encoding="utf-8")
    existing = set()
    for line in source.splitlines():
        match = re.match(r"\s*'((?:[^'" + BS + BS + r"]|" + BS + BS + r".)*)'\s*:", line)
        if match:
            existing.add(match.group(1).replace(BS + "'", "'"))
    def esc(text: str) -> str:
        return text.replace("'", BS + "'")
    added = [f"  '{esc(k)}': '{esc(v)}'," for k, v in PAIRS.items() if k not in existing]
    index = source.rstrip().rfind("};")
    source = source[:index] + "  // Real-device walkthrough, second pass (corrected tool/l10n_audit.py)\n" + "\n".join(added) + "\n" + source[index:]
    path.write_text(source, encoding="utf-8")
    print(len(added), "entries added")
    return 0


if __name__ == "__main__":
    sys.exit(main())
